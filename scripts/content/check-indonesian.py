#!/usr/bin/env python3
"""Cross-check the Indonesian meanings of words and kanji against a dictionary.

The Indonesian meanings are written by hand. This script does not write any: for each item it looks
up the English meaning in the Open Multilingual Wordnet (English WordNet + Wordnet Bahasa, MIT) and
checks whether the Indonesian meaning shares a word (or a word stem) with the dictionary's
Indonesian translations. Items that do not are listed in docs/review/indonesian-meanings.md for a
person to review. A mismatch is not necessarily an error: the dictionary only knows general senses.

    pip install wn && python3 scripts/content/check-indonesian.py
"""
import json, re, sys
from pathlib import Path

import wn

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs/review/indonesian-meanings.md"
POS = {"noun": "n", "pronoun": "n", "verb": "v", "adjective": "a", "adverb": "r"}
PREFIXES = ("memper", "meng", "meny", "mem", "men", "me", "ber", "ter", "per", "pe", "di", "ke", "se")
SUFFIXES = ("kan", "an", "i", "nya")

def lexicons():
    wn.config.data_directory = str(Path.home() / ".cache/wn")
    for spec in ("omw-en:1.4", "omw-id:1.4"):
        try:
            wn.lexicons(lexicon=spec)
        except wn.Error:
            wn.download(spec, progress_handler=None)
        if not wn.lexicons(lexicon=spec):
            wn.download(spec, progress_handler=None)
    return wn.Wordnet("omw-en:1.4")

def english_terms(text):
    text = re.sub(r"\(.*?\)", "", text)
    for part in re.split(r"[,;/]", text):
        part = part.strip().lower()
        part = re.sub(r"^(to|a|an|the) ", "", part)
        if part:
            yield part

def stems(word):
    word = word.lower()
    out = {word}
    for p in PREFIXES:
        if word.startswith(p) and len(word) - len(p) >= 3:
            out.add(word[len(p):])
    for w in list(out):
        for s in SUFFIXES:
            if w.endswith(s) and len(w) - len(s) >= 3:
                out.add(w[: -len(s)])
    return out

def words(text):
    text = re.sub(r"\(.*?\)", " ", text.lower())
    return {w for w in re.findall(r"[a-z]+(?:-[a-z]+)?", text) if len(w) >= 3}

def check(en_wn, en, id_, pos):
    translations = set()
    for term in english_terms(en):
        for ss in en_wn.synsets(term, pos=POS.get(pos)) or en_wn.synsets(term):
            for t in ss.translate(lang="id"):
                translations.update(l.lower() for l in t.lemmas())
    if not translations:
        return "no-data", []
    mine = set().union(*(stems(w) for w in words(id_))) if words(id_) else set()
    theirs = set()
    for t in translations:
        for w in re.findall(r"[a-z]+", t):
            theirs |= stems(w)
    return ("match" if mine & theirs else "mismatch"), sorted(translations, key=len)[:6]

def main():
    en_wn = lexicons()
    rows, unchecked, counts = [], [], {"match": 0, "mismatch": 0, "no-data": 0}
    for f in sorted((ROOT / "data/japanese/vocabulary").glob("*.json")):
        for w in json.loads(f.read_text())["items"]:
            status, suggestions = check(en_wn, w["meaning"]["en"], w["meaning"]["id"], w["partOfSpeech"])
            counts[status] += 1
            if status == "mismatch":
                rows.append((f.stem, w.get("kanji") or w["kana"], w["kana"], w["meaning"]["en"], w["meaning"]["id"], suggestions))
            elif status == "no-data":
                unchecked.append((f.stem, w.get("kanji") or w["kana"], w["meaning"]["en"], w["meaning"]["id"]))
    for f in sorted((ROOT / "data/japanese/kanji").glob("*.json")):
        for k in json.loads(f.read_text())["items"]:
            status, suggestions = check(en_wn, k["meanings"]["en"], k["meanings"]["id"], None)
            counts[status] += 1
            if status == "no-data":
                unchecked.append((f"kanji {f.stem}", k["character"], k["meanings"]["en"], k["meanings"]["id"]))
            if status == "mismatch":
                rows.append((f"kanji {f.stem}", k["character"], "", k["meanings"]["en"], k["meanings"]["id"], suggestions))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Indonesian meanings to review",
        "",
        "Generated by `scripts/content/check-indonesian.py`. Each Indonesian meaning was compared with the Indonesian",
        "translations that the Open Multilingual Wordnet (Wordnet Bahasa, MIT) gives for the English meaning.",
        "The items below share no word with the dictionary. Many are still right (the dictionary knows general senses,",
        "not the one a learner needs); check each and correct the meaning in the data file if it is wrong.",
        "",
        f"- Match: {counts['match']}",
        f"- To review: {counts['mismatch']}",
        f"- Not in the dictionary (not checked): {counts['no-data']}",
        "",
        "| File | Word | Kana | English | Indonesian (ours) | Dictionary suggests |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for file, word, kana, en, id_, sug in rows:
        lines.append(f"| {file} | {word} | {kana} | {en} | {id_} | {', '.join(sug)} |")
    lines += ["", "## Not in the dictionary", "", "These could not be checked automatically (grammar words, set phrases, katakana words, counters).", "",
              "| File | Word | English | Indonesian (ours) |", "| --- | --- | --- | --- |"]
    lines += [f"| {a} | {b} | {c} | {d} |" for a, b, c, d in unchecked]
    OUT.write_text("\n".join(lines) + "\n")
    print(counts, "->", OUT.relative_to(ROOT))

main()
